import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

import streamlit as st
from frontend.api_client import api
from frontend.components.ui import (
    render_section_header, render_status_pill
)


def render_settings():
    render_section_header("Settings & Administration", "Configure backend connectivity, maintenance operations, and system diagnosis")

    st.subheader("🌐 Backend REST API Connection")
    c_url, c_btn = st.columns([3, 1])
    with c_url:
        new_url = st.text_input("Flask API URL", value=api.base_url, key="input_backend_url")
    with c_btn:
        st.write("")
        st.write("")
        if st.button("Test Connection"):
            api.set_base_url(new_url)
            h = api.check_health()
            if h.get("success"):
                st.success("✅ Backend is reachable and healthy!")
            else:
                st.error(f"❌ Backend check failed: {h.get('error', {}).get('message')}")

    st.markdown("<hr>", unsafe_allow_html=True)
    st.subheader("⚙️ Maintenance & Actions")

    col_m1, col_m2 = st.columns(2)
    with col_m1:
        st.markdown("#### 🔄 Reload Official Sample Data")
        st.write("Resets the database and loads CSE departments, professors, courses, enrollments, prerequisites, and 15 FOL rules.")
        chk_reload = st.checkbox("Confirm database reset and reload", key="chk_set_reload")
        if st.button("Reload Sample Dataset", disabled=not chk_reload, type="primary"):
            with st.spinner("Seeding database..."):
                s_res = api.seed_sample_data()
                if s_res.get("success"):
                    st.success("Database successfully reset and loaded with college data!")
                else:
                    st.error(s_res.get("error", {}).get("message", "Reload failed."))

    with col_m2:
        st.markdown("#### 🧹 Clear Inferred Facts")
        st.write("Deletes all dynamically inferred facts generated by forward chaining, leaving only ground base facts.")
        if st.button("Clear Inferred Facts", key="btn_set_clr_inf"):
            c_res = api.clear_inferred_facts()
            if c_res.get("success"):
                st.success(f"Cleared {c_res['data']['deleted_count']} inferred facts!")
            else:
                st.error("Failed to clear inferred facts.")

        st.markdown("<br>", unsafe_allow_html=True)
        st.markdown("#### 🗑️ Clear Query History")
        st.write("Wipes all natural language question logs and reasoning traces from the database.")
        if st.button("Clear Query History", key="btn_set_clr_qh"):
            qh_res = api.clear_query_history()
            if qh_res.get("success"):
                st.success("Query history successfully cleared!")
            else:
                st.error("Failed to clear query history.")

    st.markdown("<hr>", unsafe_allow_html=True)
    st.subheader("ℹ️ System Architecture & FOL Engine Specifications")
    st.markdown("""
    - **Logic Reasoner**: Custom pure Python first-order logic engine implementing **SLD Backward Resolution** and **Fixpoint Forward Chaining**.
    - **Closed-World Assumption (CWA)**: Any ground relation not provable from known facts and active rules resolves to `FALSE`. Entities absent from the knowledge base resolve to `UNKNOWN`.
    - **Safety Condition**: Every rule head variable must occur within at least one body atom clause.
    - **Unification**: Martelli-Montanari term dereferencing and standardized-apart variable renaming.
    - **Database**: SQLite with foreign key cascades and atomic entity-to-fact synchronization.
    """)


if __name__ == "__main__":
    render_settings()

